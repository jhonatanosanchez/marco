#!/usr/bin/env node
// Builds the colour emoji font the admin's emoji picker and the display share: a subset of Noto Color Emoji
// (COLRv1) with only the emoji the picker offers (web/admin/emoji-data.ts) and the default icon rules
// (server/core/iconRules.js). It is served from the app itself, so the picker shows the same glyphs as the TV and
// a strict Content-Security-Policy (font-src 'self') still allows it.
//
//   pip install fonttools brotli          (fontTools keeps the COLR and CPAL colour tables when subsetting)
//   node scripts/build-emoji-font.mjs <path to Noto-COLRv1.ttf>
//   node scripts/build-emoji-font.mjs --check      exit 1 when the picker or the icon rules changed since the build
//
// Source font: https://github.com/googlefonts/noto-emoji (2D/fonts/Noto-COLRv1.ttf), SIL Open Font License 1.1
// (web/shared/fonts/OFL.txt). Writes:
//   web/shared/fonts/marco-emoji.woff2   the subset
//   web/shared/emoji-font.css            @font-face "Marco Emoji" with a unicode-range of the subset's code points
//   web/shared/emojiFont.json            the emoji list the font was built from (checked by the tests)
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const FONT_OUT = resolve(root, 'web/shared/fonts/marco-emoji.woff2');
const CSS_OUT = resolve(root, 'web/shared/emoji-font.css');
export const MANIFEST_PATH = resolve(root, 'web/shared/emojiFont.json');

/** Every emoji the picker offers and the default icon rules use, in a stable order, without duplicates. */
export function fontEmoji() {
  const picker = readFileSync(resolve(root, 'web/admin/emoji-data.ts'), 'utf8');
  const rules = readFileSync(resolve(root, 'server/core/iconRules.js'), 'utf8');
  const list = [
    ...[...picker.matchAll(/icon: '([^']+)'/g)].map((m) => m[1]),
    ...[...picker.matchAll(/^\s*'(\S+) [^']*'/gm)].map((m) => m[1]),
    ...[...rules.matchAll(/emoji: '([^']+)'/g)].map((m) => m[1]),
  ];
  return [...new Set(list)].sort();
}

/** Code points of `emoji` as CSS unicode-range parts ("U+2600-2601, U+1F382"), ASCII left out (keycap bases). */
export function unicodeRange(emoji) {
  const cps = [...new Set(emoji.flatMap((e) => [...e].map((c) => c.codePointAt(0))))].filter((c) => c > 0x7f).sort((a, b) => a - b);
  const parts = [];
  for (let i = 0; i < cps.length; i++) {
    let j = i;
    while (j + 1 < cps.length && cps[j + 1] === cps[j] + 1) j++;
    const hex = (n) => n.toString(16).toUpperCase();
    parts.push(i === j ? `U+${hex(cps[i])}` : `U+${hex(cps[i])}-${hex(cps[j])}`);
    i = j;
  }
  return parts.join(', ');
}

function css(range) {
  return `/* Generated by scripts/build-emoji-font.mjs. Do not edit by hand. */
/* Noto Color Emoji subset (SIL Open Font License 1.1, see fonts/OFL.txt): the emoji of the admin's picker and the
   default icon rules. Browsers without COLRv1 colour fonts skip it and use the next emoji font in the stack. */
@font-face {
  font-family: 'Marco Emoji';
  src: url('./fonts/marco-emoji.woff2') format('woff2') tech(color-COLRv1);
  font-display: swap;
  unicode-range: ${range};
}
`;
}

const args = process.argv.slice(2);
if (import.meta.url === `file://${process.argv[1]}`) {
  const emoji = fontEmoji();
  if (args[0] === '--check') {
    const built = JSON.parse(readFileSync(MANIFEST_PATH, 'utf8')).emoji;
    const missing = emoji.filter((e) => !built.includes(e));
    if (missing.length) {
      console.error(`emoji font is out of date, missing: ${missing.join(' ')}. Rebuild it (see scripts/build-emoji-font.mjs).`);
      process.exit(1);
    }
    console.log(`emoji font up to date (${built.length} emoji)`);
  } else {
    const source = args[0];
    if (!source) {
      console.error('usage: node scripts/build-emoji-font.mjs <Noto-COLRv1.ttf> | --check');
      process.exit(1);
    }
    const work = mkdtempSync(join(tmpdir(), 'marco-emoji-'));
    let font;
    try {
      const text = join(work, 'emoji.txt');
      writeFileSync(text, emoji.join(''));
      execFileSync('python3', ['-m', 'fontTools.subset', resolve(source), `--text-file=${text}`, '--flavor=woff2', `--output-file=${FONT_OUT}`, '--layout-features=*', '--no-hinting'], { stdio: 'inherit' });
      font = readFileSync(FONT_OUT);
    } catch (err) {
      console.error(`subsetting failed (${err.message}). Is fontTools installed? pip install fonttools brotli`);
      process.exit(1);
    } finally {
      rmSync(work, { recursive: true, force: true });
    }
    writeFileSync(CSS_OUT, css(unicodeRange(emoji)));
    writeFileSync(MANIFEST_PATH, `${JSON.stringify({ source: 'Noto Color Emoji (COLRv1), github.com/googlefonts/noto-emoji', license: 'OFL-1.1', emoji }, null, 2)}\n`);
    console.log(`${emoji.length} emoji, ${(font.length / 1024).toFixed(0)} KB → ${FONT_OUT}`);
  }
}
